import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8');
const catalog = JSON.parse(read('../themes.json'));
const css = read('../src/gallery.css');
const palette = read('../src/palette.js').replaceAll(/^export /gm, '');
const client = read('../src/client.js');
const body = [
  `const catalog = ${JSON.stringify(catalog, null, 2)};`,
  `const galleryCss = ${JSON.stringify(css)};`,
  palette.trim(),
  client.trim(),
].join('\n\n').split('\n').map((line) => line ? `    ${line}` : '').join('\n');
const bundle = `// Generated by npm run build. Edit src/ or themes.json.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-work-skin',\n  factory(require) {\n${body}\n  },\n});\n`;
const target = new URL('../lib/client.js', import.meta.url);

if (process.argv.includes('--check')) {
  assert.ok(readFileSync(target, 'utf8') === bundle, 'Run npm run build to refresh lib/client.js');
} else {
  writeFileSync(target, bundle);
}
